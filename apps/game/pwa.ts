/**
 * Installable web version (lot L8.2, D-24): at build time, writes the web app manifest and a service worker that keeps
 * every file of the game on the device, so the game opens without network once installed (iPhone: Safari → Share →
 * « Sur l'écran d'accueil »). No dependency: the list of files comes from Vite's own bundle. Texts come from
 * content/i18n (no text in code).
 */
import { readdirSync, readFileSync, statSync } from 'node:fs';
import { join, relative } from 'node:path';
import { parse } from 'yaml';
import type { Plugin } from 'vite';

/** Files of a folder, as paths relative to it with forward slashes. */
function filesOf(dir: string, root = dir): string[] {
  return readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    return statSync(path).isDirectory() ? filesOf(path, root) : [relative(root, path).replace(/\\/g, '/')];
  });
}

/** The service worker: precache everything, then cache first; old caches are dropped when a new version arrives. */
function serviceWorker(cache: string, files: string[]): string {
  return `// Generated by apps/game/pwa.ts — do not edit.
const CACHE = ${JSON.stringify(cache)};
const FILES = ${JSON.stringify(files)};
self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES)).then(() => self.skipWaiting()));
});
self.addEventListener('activate', (e) => {
  e.waitUntil(caches.keys().then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim()));
});
self.addEventListener('fetch', (e) => {
  const req = e.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== self.location.origin) return;
  // Pages (with or without review settings in the address) are always the game's single page. ignoreVary: the
  // scripts are asked with an Origin header (crossorigin) and the server answers « Vary: Origin ».
  const key = req.mode === 'navigate' ? './index.html' : req;
  e.respondWith(caches.open(CACHE).then((c) => c.match(key, { ignoreSearch: req.mode === 'navigate', ignoreVary: true }).then((hit) => hit || fetch(req).then((res) => {
    if (res.ok) c.put(req, res.clone());
    return res;
  }))));
});
`;
}

export function pwa(options: { version: string; i18n: string; publicDir: string }): Plugin {
  return {
    name: 'neutron-pwa',
    apply: 'build',
    generateBundle(_out, bundle) {
      const texts = parse(readFileSync(options.i18n, 'utf8')) as Record<string, string>;
      const manifest = {
        name: texts['app.title'],
        short_name: texts['app.title'],
        description: texts['app.subtitle'],
        lang: 'fr',
        start_url: './',
        scope: './',
        display: 'fullscreen',
        orientation: 'landscape',
        background_color: '#BFE3FF',
        theme_color: '#1D47B8',
        icons: [
          { src: 'icons/icone-192.png', sizes: '192x192', type: 'image/png', purpose: 'any' },
          { src: 'icons/icone-512.png', sizes: '512x512', type: 'image/png', purpose: 'any' },
          { src: 'icons/icone-512-plein.png', sizes: '512x512', type: 'image/png', purpose: 'maskable' },
        ],
      };
      this.emitFile({ type: 'asset', fileName: 'manifest.webmanifest', source: JSON.stringify(manifest, null, 2) });
      const files = ['./', './index.html', 'manifest.webmanifest', ...Object.keys(bundle), ...filesOf(options.publicDir)]
        .filter((f) => !f.endsWith('.map'))
        .map((f) => (f.startsWith('./') ? f : `./${f}`));
      const unique = [...new Set(files)].sort();
      // The cache name changes with the version and the list of hashed files, so a new build replaces the old cache.
      let hash = 0;
      for (const ch of unique.join('|')) hash = (hash * 31 + ch.charCodeAt(0)) >>> 0;
      this.emitFile({ type: 'asset', fileName: 'sw.js', source: serviceWorker(`nuki-town-${options.version}-${hash.toString(36)}`, unique) });
    },
  };
}
